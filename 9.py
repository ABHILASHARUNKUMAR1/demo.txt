# Python Data Types

# Integer
a = 10
print("Integer:", a)
print(type(a))

# Float
b = 10.5
print("Float:", b)
print(type(b))

# String
name = "Python"
print("String:", name)
print(type(name))

# Boolean
c = True
print("Boolean:", c)
print(type(c))

# List
my_list = [10, 20, 30, 40]
print("List:", my_list)
print(type(my_list))

# Tuple
my_tuple = (10, 20, 30)
print("Tuple:", my_tuple)
print(type(my_tuple))

# Set
my_set = {10, 20, 30}
print("Set:", my_set)
print(type(my_set))

# Dictionary
my_dict = {"name": "John", "age": 20}
print("Dictionary:", my_dict)
print(type(my_dict))
